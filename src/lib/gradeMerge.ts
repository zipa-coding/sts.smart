/**
 * Menggabungkan deskripsi nilai lama dan baru secara aman agar deskripsi siswa
 * tidak pernah tertimpa atau hilang secara tidak sengaja.
 *
 * Aturan:
 * 1. Jika deskripsiBaru undefined atau null, kembalikan deskripsiLama.
 * 2. Jika deskripsiBaru kosong ("" / hanya spasi) dan deskripsiLama berisi teks,
 *    kembalikan deskripsiLama kecuali izinKosongkan === true.
 * 3. Selain itu kembalikan deskripsiBaru.
 */
export function mergeDeskripsiAman(
  deskripsiLama: string | undefined,
  deskripsiBaru: string | undefined,
  izinKosongkan: boolean
): string {
  const lama = deskripsiLama ?? "";

  if (deskripsiBaru === undefined || deskripsiBaru === null) {
    return lama;
  }

  if (deskripsiBaru.trim() === "" && lama.trim() !== "") {
    if (izinKosongkan === true) {
      return deskripsiBaru;
    }
    return lama;
  }

  return deskripsiBaru;
}

export interface HasilDeskripsiAwalForm {
  customDescription: string;
  isCustomDescActive: boolean;
}

/**
 * Menentukan kondisi awal deskripsi pada form guru (TeacherPanel) saat memuat dokumen grade:
 * 1. Jika deskripsi berisi teks, gunakan teks dari dokumen (isCustomDescActive menyesuaikan apakah berbeda dari teks otomatis).
 * 2. Jika deskripsi kosong dan deskripsiDikosongkan === true ("kosong sengaja"),
 *    kembalikan customDescription = "" dan isCustomDescActive = true (jangan jatuh ke teks otomatis).
 * 3. Jika penanda tidak ada / false dan deskripsi kosong (dokumen lama atau belum pernah diisi),
 *    gunakan teks otomatis (autoGeneratedText) dan isCustomDescActive = false.
 */
export function tentukanDeskripsiAwalForm(
  deskripsiTersimpan: string | undefined | null,
  deskripsiDikosongkan: boolean | undefined | null,
  autoGeneratedText: string
): HasilDeskripsiAwalForm {
  const rawExisting =
    typeof deskripsiTersimpan === "string" ? deskripsiTersimpan.trim() : "";

  if (rawExisting !== "") {
    const isTrulyManual =
      !autoGeneratedText ||
      rawExisting.toLowerCase() !== autoGeneratedText.toLowerCase().trim();
    return {
      customDescription: rawExisting,
      isCustomDescActive: isTrulyManual,
    };
  }

  if (deskripsiDikosongkan === true) {
    return {
      customDescription: "",
      isCustomDescActive: true,
    };
  }

  return {
    customDescription: autoGeneratedText || "",
    isCustomDescActive: false,
  };
}

